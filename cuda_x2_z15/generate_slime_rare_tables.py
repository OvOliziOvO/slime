"""Generate the Java nextInt(10) rejection tables used by the CUDA search."""
import argparse
from bisect import bisect_left
from pathlib import Path

MASK = (1 << 48) - 1
MULTIPLIER = 0x5DEECE66D
INVERSE = 0xDFE05BCB1365
SCRAMBLE = 0x5E434E432
X_SQUARE = 0x4C1906
X_LINEAR = 0x5AC0DB
BUCKET_SIZE = 1 << 32
LIMIT = (1 << 31) - 8

def rejection_targets():
    assert (MULTIPLIER * INVERSE) & MASK == 1
    targets = []
    for rejected in range((1 << 48) - (16 << 16), 1 << 48):
        state = rejected
        while True:
            state = (state * MULTIPLIER + 11) & MASK
            bits = state >> 17
            if bits < LIMIT:
                break
        if bits % 10 == 0:
            targets.append((((rejected - 11) * INVERSE) & MASK) ^ SCRAMBLE)
    targets.sort()
    assert len(targets) == len(set(targets)) == 104848
    period = 1 << 48
    # The signed X term can span one neighboring bucket on either side.
    return ([v - period for v in targets[bisect_left(targets, period - BUCKET_SIZE):]]
            + targets
            + [v + period for v in targets[:bisect_left(targets, BUCKET_SIZE)]])

def inverse_table():
    table = [None] * 256
    for x in range(256):
        value = (X_SQUARE * x * x + X_LINEAR * x) & 255
        assert table[value] is None
        inverse_derivative = pow((2 * X_SQUARE * x + X_LINEAR) & 255, -1, 256)
        table[value] = x | (inverse_derivative << 8)
    assert all(value is not None for value in table)
    return table

def write_array(path, name, kind, suffix, values):
    path.write(f"static __device__ const {kind} {name}[{len(values)}] = {{\n")
    for start in range(0, len(values), 12):
        line = ", ".join(f"{value}{suffix}" for value in values[start:start + 12])
        path.write(f"    {line},\n")
    path.write("};\n")

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    targets = rejection_targets()
    offsets = [bisect_left(targets, i * BUCKET_SIZE) for i in range(-1, 65538)]
    assert offsets[0] == 0 and offsets[-1] == len(targets)
    with args.output.open("w", encoding="ascii") as output:
        output.write("// Generated by generate_slime_rare_tables.py.\n")
        write_array(output, "SLIME_RARE_TARGETS", "uint64_t", "ULL", [v & MASK for v in targets])
        write_array(output, "SLIME_RARE_OFFSETS", "uint32_t", "U", offsets)
        write_array(output, "SLIME_X_MOD256_INVERSE", "uint32_t", "U", inverse_table())

if __name__ == "__main__":
    main()

